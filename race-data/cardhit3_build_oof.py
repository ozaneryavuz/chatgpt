#!/usr/bin/env python3
"""Build CardHit-3 card-linked OOF rows from official TJK block CSV pairs.

The output directly closes the missing-artifact contract:

    date, card_id, leg, betting_interest, winner,
    agf_prob, ganyan_prob, conditional_prob,
    pairwise_prob, lambdamart_prob

Implementation rules
--------------------
* The result CSV first column is finish order, never the program number.
* Result rows are joined to program rows by date/track/race/normalised horse.
* Coupled horses are collapsed into one coupon betting interest.
* Entity-history features use dates strictly earlier than the prediction date;
  all meetings on the same day are snapshotted before that day's results update
  the feature state.
* OOF probabilities are generated by expanding date folds. No row is predicted
  by a model trained on the same date or a future date.
* Historical Ganyan is the final pre-off market quote from the official result
  export. It is explicitly labelled so it is not confused with an early live
  quote used on a future card.
"""

